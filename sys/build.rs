use std::collections::HashSet;
use std::path::PathBuf;

use normpath::PathExt;

fn main() {
    // include path openvr/headers
    let include_path = relative("openvr/headers");
    // This assumes all your C++ bindings are in main.rs
    let mut b = autocxx_build::Builder::new(relative("src/lib.rs"), [&include_path])
        .build()
        .expect("Could not autogenerate bindings");
    // arbitrary library name, pick anything
    b.flag_if_supported("-std=c++14").compile("foobar");
    println!("cargo:rerun-if-changed=src/lib.rs");

    generate_checked_enums();

    // Link the C++ libraries
    #[cfg(target_os = "windows")]
    let input_files = [
        relative("openvr/bin/win64/openvr_api.dll"),
        relative("openvr/lib/win64/openvr_api.lib"),
    ];
    #[cfg(all(target_os = "linux", target_arch = "x86_64"))]
    let input_files = [relative("openvr/bin/linux64/libopenvr_api.so")];
    #[cfg(all(target_os = "linux", target_arch = "x86"))]
    let input_files = [relative("openvr/bin/linux32/libopenvr_api.so")];
    #[cfg(target_os = "macos")]
    let input_files: [PathBuf; 1] = [panic!("Mac is unsupported")];

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    for f in input_files {
        let file_name = f.file_name().unwrap();
        std::fs::copy(&f, out_dir.join(file_name)).unwrap_or_else(|err| {
            panic!("Failed to copy {:?} to {:?}: {err}", file_name, &out_dir)
        });
    }

    println!("cargo:rustc-link-lib=dylib=openvr_api");
    println!("cargo:rustc-link-search=native={:?}", out_dir);
}

/// The enums that a runtime hands us as a plain integer, with the smallest number of ids we
/// expect to read for each. SteamVR ships separately from these headers, so it can name an
/// id that the generated enum has no variant for, and building the enum out of such an id is
/// undefined behaviour. Each entry gets a `from_raw` that only answers for ids the header
/// states, so the caller decides what an unnamed one means.
const CHECKED_ENUMS: [(&str, usize); 4] = [
    ("EVREventType", 150),
    ("ETrackedDeviceClass", 6),
    ("ETrackedControllerRole", 6), // Max repeats the id of Stylus

    ("EDeviceActivityLevel", 6),
];

/// Writes a `from_raw` for each of [`CHECKED_ENUMS`], read out of the same header autocxx
/// generates the enums from. That keeps the two in step: update the header and these update
/// with it, so no hand written table can fall behind.
fn generate_checked_enums() {
    let header_path = relative("openvr/headers/openvr.h");
    let header = std::fs::read_to_string(&header_path).expect("Could not read openvr.h");
    let mut code = String::from("// @generated by build.rs from openvr/headers/openvr.h\n");
    for (name, minimum) in CHECKED_ENUMS {
        code += &checked_enum(&header, name, minimum);
    }
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out_dir.join("checked_enums.rs"), code)
        .expect("Could not write checked_enums.rs");
    println!("cargo:rerun-if-changed={}", header_path.display());
}

fn checked_enum(header: &str, name: &str, minimum: usize) -> String {
    let declaration = header
        .split_once(&format!("enum {name}"))
        .unwrap_or_else(|| panic!("openvr.h no longer declares enum {name}"))
        .1;
    assert!(
        declaration.trim_start().starts_with('{'),
        "openvr.h declares enum {name} in a shape this does not read"
    );
    let body = declaration
        .split_once('{')
        .unwrap_or_else(|| panic!("enum {name} has no body"))
        .1
        .split_once("};")
        .unwrap_or_else(|| panic!("enum {name} body is unterminated"))
        .0;

    let mut arms = String::new();
    let mut ids = HashSet::new();
    for line in body.lines() {
        let entry = line.split("//").next().unwrap().trim().trim_end_matches(',');
        let Some((variant, id)) = entry.split_once('=') else {
            continue;
        };
        let variant = variant.trim();
        if variant.is_empty() || !variant.chars().all(|c| c.is_alphanumeric() || c == '_') {
            continue;
        }
        // An id stated in a form this does not read stays unknown at runtime, which is the
        // safe outcome. The count assert below catches a header that stops parsing entirely.
        let Ok(id) = id.trim().parse::<i32>() else {
            continue;
        };
        if !ids.insert(id) {
            continue;
        }
        arms += &format!("            {id} => Some(Self::{variant}),\n");
    }
    assert!(
        ids.len() >= minimum,
        "Only read {} ids for enum {name} in openvr.h, expected at least {minimum}, so its \
         declaration must have changed shape",
        ids.len()
    );

    format!(
        "impl crate::ffi::vr::{name} {{
    /// The variant with this id, or `None` when openvr.h does not name the id.
    pub fn from_raw(raw: i32) -> Option<Self> {{
        match raw {{
{arms}            _ => None,
        }}
    }}
}}
"
    )
}

fn relative(s: &str) -> PathBuf {
    let result = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    result.join(s).normalize().unwrap().into_path_buf()
}
